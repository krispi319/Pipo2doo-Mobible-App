package ai.mwm.client.data
import java.time.*
fun main() {
 var checks=0
 fun verify(ok:Boolean,label:String){check(ok){label};checks++;println("PASS $label")}
 val utc=ZoneId.of("UTC");val day=LocalDate.of(2026,10,17).toEpochDay()
 fun at(hour:Int)=LocalDate.ofEpochDay(day).atTime(hour,0).atZone(utc).toInstant().toEpochMilli()
 val t=Task(title="Test",day=day,minute=12*60)
 verify(!t.reminder,"new tasks default to no nudge")
 verify(!missedDeadline(t,at(11),utc),"future deadline not red")
 verify(missedDeadline(t,at(13),utc),"unfinished past deadline red")
 val done=t.copy(status=TaskStatus.Done,completedAt=at(11))
 verify(completionDay(done,utc)==day,"completion uses actual completed date")
 verify(!missedDeadline(done,at(13),utc),"on-time completion not red")
 val late=t.copy(status=TaskStatus.Done,completedAt=at(13))
 verify(missedDeadline(late,at(14),utc),"late completion keeps missed deadline")
 val tomorrow=t.copy(status=TaskStatus.Done,completedAt=at(13)+86_400_000)
 verify(completionDay(tomorrow,utc)==day+1 && missedDeadline(tomorrow,at(13)+86_400_000,utc),"late completion green on finish day and red on due day")
 val anytime=t.copy(minute=null)
 verify(!missedDeadline(anytime,at(23),utc),"all-day task not missed before midnight")
 verify(missedDeadline(anytime,at(1)+86_400_000,utc),"all-day task missed next day")
 verify(missedDeadline(anytime.copy(status=TaskStatus.Done,completedAt=at(0)+86_400_000),at(1)+86_400_000,utc),"midnight completion belongs to next day")
 verify(completionDay(done.copy(completedAt=at(23)),ZoneId.of("Asia/Tokyo"))==day+1,"completion day respects calendar timezone")
 verify(completionDay(done.copy(completedAt=0),utc)==null,"unknown completion date not invented")
 verify(completionDay(t.copy(completedAt=at(11)),utc)==null,"reopened task not a completed record")
 verify(partnerClockZone(Preferences())==null,"unknown partner clock not guessed")
 val p=Preferences(clockZone="Europe/Berlin",partnerClockZone="Asia/Ho_Chi_Minh")
 verify(clockZone(p.clockZone).id=="Europe/Berlin","selected own timezone valid")
 verify(partnerClockZone(p)?.id=="Asia/Ho_Chi_Minh","partner shared timezone used")
 verify(partnerClockZone(p.copy(partnerClockOverride="America/New_York"))?.id=="America/New_York","optional partner override wins locally")
 verify(clockZone("bad-zone")==ZoneId.systemDefault(),"invalid saved timezone falls back safely")
 val next=p.copy(partnerClockOverride="UTC").startNewCouple(day)
 verify(next.partnerClockOverride.isBlank() && next.partnerClockZone.isBlank(),"new partner clears former partner clock")
 val own=mapOf("name" to "Kris","avatar" to 2,"photo" to "cloud:space/photo.jpg")
 val restored=restoreSharedProfile(p,own,mapOf("name" to "Bo","timezone" to "Asia/Tokyo"),"Partner")
 verify(restored.shareProfile && restored.partnerClockZone=="Asia/Tokyo","profile always shared and partner timezone hydrated")
 val n=Appreciation(kind="Message",message="Hi",replyTo="quoted-id")
 verify(n.replyTo=="quoted-id" && chatDelivery(n,null,setOf(n.id),true)=="Seen","reply reference and Seen indicator")
 println("$checks v1.3.0 model checks passed")
}
